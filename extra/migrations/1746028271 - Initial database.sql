CREATE TABLE "incarcare" (
	"id"	INTEGER UNIQUE,
	"data"	INTEGER NOT NULL UNIQUE,
	"siloz"	INTEGER NOT NULL,
	"greutate"	INTEGER NOT NULL,
	PRIMARY KEY("id" AUTOINCREMENT)
);

CREATE TABLE "descarcare" (
	"id"	INTEGER UNIQUE,
	"data"	INTEGER NOT NULL UNIQUE,
	"siloz"	INTEGER NOT NULL,
	"greutate"	INTEGER NOT NULL,
	"hala"	INTEGER NOT NULL,
	"buncar"	INTEGER NOT NULL,
	PRIMARY KEY("id" AUTOINCREMENT)
);

CREATE TABLE "logs" (
	"id"	INTEGER UNIQUE,
	"data"	INTEGER NOT NULL,
	"msg"	TEXT NOT NULL,
	PRIMARY KEY("id" AUTOINCREMENT)
);